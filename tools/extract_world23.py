"""Extract World 2-3 streams, terrain tables and exact ROM metatiles."""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

from PIL import Image

from extract_smb_assets import (
    METATILE_COUNTS,
    compose_metatile,
    compose_sprite,
    find_once,
)


ROOT = Path(__file__).resolve().parents[1]
EXPECTED = "f61548fdf1670cffefcc4f0b7bdcdd9eaba0c226e3b74f8666071496988248de"
SIGNATURES = {
    "AREA": ("90110f266e108b17af32d862", 0xFD),
    "ENEMIES": ("0f02784048cef8c3f8c30f07", 0xFF),
}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--rom", type=Path, default=ROOT / "roms/Super Mario Bros. (World).nes"
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=ROOT / "scripts/generated/world23_data.nut",
    )
    args = parser.parse_args()
    raw = args.rom.read_bytes()
    if hashlib.sha256(raw).hexdigest() != EXPECTED:
        parser.error("ROM does not match the verified baseline")
    prg, chr_data = raw[16:32784], raw[32784:40976]
    metadata: dict = {"rom_sha256": EXPECTED, "streams": {}, "graphics": {}}
    lines = ["// Generated by tools/extract_world23.py from the verified ROM."]
    for name, (signature, terminator) in SIGNATURES.items():
        start = find_once(prg, bytes.fromhex(signature), f"World 2-3 {name}")
        data = prg[start : prg.index(terminator, start) + 1]
        metadata["streams"][name] = {
            "cpu_address": hex(0x8000 + start),
            "length": len(data),
            "sha256": hashlib.sha256(data).hexdigest(),
        }
        lines.append(
            f"ROM_WORLD_2_3_{name} <- ["
            + ",".join(str(value) for value in data)
            + "];"
        )
    masks = bytes.fromhex(
        "00000018011807180f18ff18011f071f0f1f811f01008f1ff11ff918f118ff1f"
    )
    mask_offset = find_once(prg, masks, "TerrainRenderBits")
    mask_data = prg[mask_offset : mask_offset + 32]
    lines.append(
        "ROM_WORLD_2_3_TERRAIN_MASKS <- ["
        + ",".join(str(value) for value in mask_data)
        + "];"
    )
    reference = find_once(prg, bytes.fromhex("f8a070bd002020200000"), "flying fish Y reference")
    lines.append("ROM_WORLD_2_3_FISH_Y_REFERENCE <- [" + ",".join(str(v) for v in prg[reference:reference+16]) + "];")
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")

    palette_offset = find_once(
        prg,
        bytes.fromhex("3f00200f291a0f0f36170f0f30210f0f27170f"),
        "ground palette",
    )
    palettes = list(prg[palette_offset + 3 : palette_offset + 35])
    background_palettes = [palettes[index : index + 4] for index in range(0, 16, 4)]
    sprite_palettes = [palettes[index : index + 4] for index in range(16, 32, 4)]
    graphics_offset = find_once(
        prg, bytes.fromhex("242424242727272724242435"), "MetatileGraphics"
    )
    color_offset = find_once(prg, bytes.fromhex("272727170717"), "ColorRotatePalette")
    colors = prg[color_offset : color_offset + 6]

    out = ROOT / "assets/world23"
    out.mkdir(parents=True, exist_ok=True)
    for stale in out.glob("*.png"):
        stale.unlink()
    cursor = graphics_offset
    for group, count in enumerate(METATILE_COUNTS):
        for index in range(count):
            image = compose_metatile(
                chr_data,
                prg[cursor : cursor + 4],
                background_palettes[group],
            )
            image.save(out / f"metatile-{group * 64 + index}.png")
            cursor += 4
    # Question blocks use metatile $c1. Their question-mark colour
    # rotates through the six ColorRotatePalette values while gameplay runs.
    question_tiles = prg[
        graphics_offset
        + sum(METATILE_COUNTS[:3]) * 4
        + 4 : graphics_offset
        + sum(METATILE_COUNTS[:3]) * 4
        + 8
    ]
    for frame, colour in enumerate(colors):
        palette = list(background_palettes[3])
        palette[1] = colour
        compose_metatile(chr_data, question_tiles, palette).save(
            out / f"question-{frame}.png"
        )
        coin_start = graphics_offset + sum(METATILE_COUNTS[:3]) * 4 + 8
        compose_metatile(chr_data, prg[coin_start:coin_start + 4], palette).save(
            out / f"coin-{frame}.png"
        )
    enemy_graphics = find_once(prg, bytes.fromhex("fcfcaaabacadfcfcaeafb0b1"), "enemy graphics")
    for frame, index in enumerate((12,13)):
        image = compose_sprite(chr_data, prg[enemy_graphics+index*6:enemy_graphics+(index+1)*6], sprite_palettes[2], 3)
        compose_sprite(chr_data, prg[enemy_graphics+index*6:enemy_graphics+(index+1)*6], sprite_palettes[1], 3).transpose(Image.Transpose.FLIP_LEFT_RIGHT).save(out / f"green-fish-{frame}.png")
        # EnemyGfxHandler flips each tile vertically and swaps rows 1/2
        # for Cheeps; the blank first row stays at its original Y.
        for name, facing in ((f"fish-{frame}-right", image),
                             (f"fish-{frame}-left", image.transpose(Image.Transpose.FLIP_LEFT_RIGHT)),
                             (f"green-fish-{frame}", compose_sprite(chr_data, prg[enemy_graphics+index*6:enemy_graphics+(index+1)*6], sprite_palettes[1], 3).transpose(Image.Transpose.FLIP_LEFT_RIGHT))):
            dead = Image.new("RGBA", (16, 24))
            dead.paste(facing.crop((0, 0, 16, 8)).transpose(Image.Transpose.FLIP_TOP_BOTTOM), (0, 0))
            dead.paste(facing.crop((0, 8, 16, 24)).transpose(Image.Transpose.FLIP_TOP_BOTTOM), (0, 8))
            dead.save(out / (name + "-dead.png"))
        image.save(out / f"fish-{frame}-right.png")
        image.transpose(Image.Transpose.FLIP_LEFT_RIGHT).save(out / f"fish-{frame}-left.png")

    # Native cell textures let the shared OAM drawer hide entire offscreen
    # columns, as GetXOffscreenBits does, rather than crop a 16px quad.
    cells_dir = out / "fish-cells"
    cells_dir.mkdir(exist_ok=True)
    for path in sorted(out.glob("*fish-*.png")):
        sprite = Image.open(path).convert("RGBA")
        for row in range(3):
            for column in range(2):
                sprite.crop((column*8,row*8,column*8+8,row*8+8)).save(
                    cells_dir / f"{path.stem}-{row*2+column}.png")

    metadata["graphics"] = {
        "palette_cpu_address": hex(0x8000 + palette_offset),
        "metatile_cpu_address": hex(0x8000 + graphics_offset),
        "metatile_ids": [
            group * 64 + index
            for group, count in enumerate(METATILE_COUNTS)
            for index in range(count)
        ],
        "question_frames": len(colors),
        "flying_fish_enemy_graphics_indices": [12,13],
        "flying_fish_sprite_palette": sprite_palettes[2],
    }
    (out / "manifest.json").write_text(
        json.dumps(metadata, indent=2) + "\n", encoding="utf-8", newline="\n"
    )
    print(args.output)


if __name__ == "__main__":
    main()
