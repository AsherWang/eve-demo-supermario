"""Split checked-in sprite canvases into native 8x8 OAM cells."""
from pathlib import Path
import json
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]


def main():
    sources = sorted((ROOT / 'assets/mario').glob('*.png'))
    sources += sorted((ROOT / 'assets/world13').glob('red-*.png'))
    sources += [ROOT / 'assets/world13/platform.png']
    sources += [ROOT / 'assets/scenery/flagpole-flag.png']
    sources += sorted((ROOT / 'assets/enemies').glob('goomba*.png'))
    entries = []
    for path in sources:
        sprite = Image.open(path).convert('RGBA')
        columns, rows = sprite.width // 8, sprite.height // 8
        directory = ROOT / 'assets/oam-cells' / path.parent.name / path.stem
        directory.mkdir(parents=True, exist_ok=True)
        cells = []
        for row in range(rows):
            for column in range(columns):
                target = directory / f'{row}-{column}.png'
                sprite.crop((column*8, row*8, column*8+8, row*8+8)).save(target)
                cells.append(target.relative_to(ROOT).as_posix())
        entries.append([path.relative_to(ROOT).as_posix(), columns, rows, cells])
    target = ROOT / 'scripts/generated/oam_cells.nut'
    target.write_text('// Generated by tools/extract_oam_cells.py.\nOAM_TEXTURE_CELLS <- '
                      + json.dumps(entries, indent=2) + ';\n', encoding='utf-8')
    print(f'{len(entries)} sprite canvases: {target}')


if __name__ == '__main__':
    main()
