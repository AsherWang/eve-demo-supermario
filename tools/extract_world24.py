"""Extract World 2-4 CastleArea3 data and textures from the verified offline ROM.
Offsets $e0/$40 come from the original castle area/enemy stream index.
Castle audio is shared with World 1-4; this tool never rewrites shared assets.
"""
from extract_world14 import *
def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--rom", type=Path,
                        default=ROOT / "roms/Super Mario Bros. (World).nes")
    parser.add_argument("--origin-state", type=Path,
                        help="Mesen state at normal World 2-4 player control; required for audio")
    parser.add_argument("--mesen", type=Path, default=tool_path("mesen"))
    parser.add_argument("--audio-work", type=Path,
                        default=ROOT / "local-parity/world24-audio-capture")
    args = parser.parse_args()
    raw = args.rom.read_bytes()
    digest = hashlib.sha256(raw).hexdigest()
    if digest != EXPECTED_ROM_SHA256:
        raise SystemExit("ROM does not match the verified baseline")
    prg, chr_data = raw[16:32784], raw[32784:40976]

    area_at = locate_area_stream(prg) + 0xE0
    enemy_at = find_once(prg, ENEMY_SIGNATURE, "E_CastleArea1") + 0x40
    area_data = stream(prg, area_at)
    enemy_data = stream(prg, enemy_at, 0xFF)
    if len(area_data) != 115 or len(enemy_data) != 47:
        raise SystemExit(
            f"unexpected 2-4 stream sizes: area={len(area_data)} enemy={len(enemy_data)}"
        )

    masks_at = find_once(prg, TERRAIN_MASK_SIGNATURE, "TerrainRenderBits")
    metatile_at = find_once(prg, METATILE_SIGNATURE, "MetatileGraphics")
    palette_at = find_once(prg, CASTLE_PALETTE_SIGNATURE, "CastlePaletteData")
    bowser_palette_at = find_once(prg, BOWSER_PALETTE_SIGNATURE, "BowserPaletteData")
    enemy_gfx_at = find_once(prg, ENEMY_GFX_SIGNATURE, "EnemyGraphicsTable")

    metadata = {
        "schema": "smb-world24-assets-v1",
        "rom_sha256": digest,
        "offline_only": True,
        "levels": ["2-4"],
        "streams": {
            "AREA": {
                "label": "L_CastleArea3",
                "cpu_address": hex(0x8000 + area_at),
                "length": len(area_data),
                "sha256": hashlib.sha256(area_data).hexdigest(),
            },
            "ENEMY": {
                "label": "E_CastleArea3",
                "cpu_address": hex(0x8000 + enemy_at),
                "length": len(enemy_data),
                "sha256": hashlib.sha256(enemy_data).hexdigest(),
            },
        },
        "area_pointer": "0x62",
        "internal_area": 4,
        "level_number": 3,
        "shared_rom_level": "5-4",
    }

    generated = ROOT / "scripts/generated"
    generated.mkdir(parents=True, exist_ok=True)
    lines = [
        "// Generated by tools/extract_world24.py from the verified ROM.",
        "ROM_WORLD_2_4_AREA <- [" + ",".join(map(str, area_data)) + "];",
        "ROM_WORLD_2_4_ENEMY <- [" + ",".join(map(str, enemy_data)) + "];",
        "WORLD24_TERRAIN_MASKS <- [" + ",".join(map(str, prg[masks_at : masks_at + 32])) + "];",
        "WORLD24_CASTLE_PALETTE <- [" + ",".join(map(str, prg[palette_at + 3 : palette_at + 35])) + "];",
        "WORLD24_BOWSER_PALETTE <- [" + ",".join(map(str, prg[bowser_palette_at + 3 : bowser_palette_at + 7])) + "];",
    ]
    (generated / "world24_data.nut").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")

    out = ROOT / "assets/world24"
    out.mkdir(parents=True, exist_ok=True)
    extract_castle_hud_coins(raw, out)
    castle_palettes = [
        list(prg[palette_at + 3 + row * 4 : palette_at + 7 + row * 4])
        for row in range(8)
    ]
    tile_image(chr_data,0xff,castle_palettes[7],0,True).save(out/"sprite-zero.png")
    metatile_bytes = prg[metatile_at : metatile_at + sum(METATILE_COUNTS) * 4]
    for group, count in enumerate(METATILE_COUNTS):
        offset = sum(METATILE_COUNTS[:group]) * 4
        for index in range(count):
            code = group * 0x40 + index
            compose_metatile(
                chr_data,
                metatile_bytes[offset + index * 4 : offset + index * 4 + 4],
                castle_palettes[group],
            ).save(out / f"metatile-{code}.png")

    # Palette rotation affects castle question blocks just like HUD coins.
    rotation_at=find_once(prg,bytes.fromhex("272727170717"),"ColorRotatePalette")
    for phase,color in enumerate(prg[rotation_at:rotation_at+6]):
        palette=list(castle_palettes[3]);palette[1]=color
        for code in (0xC0,0xC1,0xC2,0xC5):
            offset=sum(METATILE_COUNTS[:3])*4+(code-0xC0)*4
            compose_metatile(chr_data,metatile_bytes[offset:offset+4],palette).save(out/f"metatile-{code}-phase-{phase}.png")

    tile_image(chr_data, 0x5b, castle_palettes[6], 0, True).save(out / "platform.png")
    compose_sprite(chr_data, bytes.fromhex("fcfcd0d0d7d7"), castle_palettes[6], 3, mirror_right=True).crop((0,8,16,24)).save(out / "podoboo.png")

    Image.open(out/"podoboo.png").transpose(Image.Transpose.FLIP_TOP_BOTTOM).save(out/"podoboo-down.png")

    # EnemyGraphicsTable stores two 8px columns per row of a 16x24 sprite.
    enemy_gfx = prg[enemy_gfx_at : enemy_gfx_at + 48 * 6]
    bowser_palette = list(prg[bowser_palette_at + 3 : bowser_palette_at + 7])
    bowser_rows = {
        "front-0": bytes.fromhex("bfbec1c0c2fc"),
        "rear-0": bytes.fromhex("c4c3c6c5c8c7"),
        "front-1": bytes.fromhex("bfbecac9c2fc"),
        "rear-1": bytes.fromhex("c4c3c6c5cccb"),
    }
    for name, tiles in bowser_rows.items():
        if tiles not in enemy_gfx:
            raise SystemExit(f"Bowser graphics row missing: {name}")
    extract_bowser_sprites(raw, out)
    for direction in ("left","right"):
        for pose in range(4):
            canvas=Image.open(out/f"bowser-{direction}-{pose}.png")
            front_x=0 if direction=="left" else 16
            canvas.crop((front_x,0,front_x+16,24)).save(out/f"bowser-front-{direction}-{pose}.png")
            rear_x=16-front_x
            canvas.crop((rear_x,8,rear_x+16,32)).save(out/f"bowser-rear-{direction}-{pose}.png")

    # Original World 2-4 saves the mushroom retainer/Toad, not the princess.
    # This is the exact six-tile entry at EnemyGraphicsTable $a2. Castle sprite
    # palette 2 and mirrored right column come from EnemyGfxHandler's OAM.
    retainer_tiles = bytes.fromhex("cdcdcececfcf")
    if retainer_tiles not in enemy_gfx:
        raise SystemExit("mushroom retainer graphics row missing")
    compose_sprite(chr_data, retainer_tiles, castle_palettes[6], 3, mirror_right=True).save(
        out / "toad.png"
    )

    # DrawFirebar writes OAM attribute $02: sprite palette 2 ($3f18),
    # not Bowser's sprite palette. Castle palette groups 0..3 are BG,
    # groups 4..7 are sprites; group 6 uses red $16 rather than green $1a.
    firebar_palette = castle_palettes[6]
    for frame, tile in enumerate((0x64, 0x65)):
        tile_image(chr_data, tile, firebar_palette, 0, True).save(
            out / f"firebar-{frame}.png"
        )
    for frame in range(2):
        Image.open(out/f"firebar-{frame}.png").transpose(Image.Transpose.ROTATE_180).save(out/f"firebar-{frame}-flipped.png")
    flame = Image.new("RGBA", (24, 8), (0, 0, 0, 0))
    for index, tile in enumerate((0x51, 0x52, 0x53)):
        flame.alpha_composite(
            tile_image(chr_data, tile, castle_palettes[6], 0, True), (index * 8, 0)
        )
    flame.save(out / "bowser-flame.png")
    flame.transpose(Image.Transpose.FLIP_TOP_BOTTOM).save(out/"bowser-flame-flipped.png")

    metadata["generated_textures"] = {
        "metatiles": "assets/world24/metatile-*.png",
        "bowser": [f"assets/world24/bowser-{direction}-{pose}.png"
                   for direction in ("left", "right") for pose in range(4)],
        "mushroom_retainer": "assets/world24/toad.png",
        "firebar": ["assets/world24/firebar-0.png", "assets/world24/firebar-1.png"],
        "flame": "assets/world24/bowser-flame.png",
    }
    metadata["audio_manifest"] = "assets/world14/audio-manifest.json"
    map_path = ROOT / "scripts/generated/world24_map.nut"
    if map_path.is_file():
        metadata["map"] = {"columns":160,"source":"ROM RenderAreaGraphics, single forward pass",
            "sha256":file_sha256(map_path),"route_evidence":False}
    (out / "manifest.json").write_text(json.dumps(metadata, indent=2) + "\n", encoding="utf-8", newline="\n")
    print(f"world24 area={metadata['streams']['AREA']['cpu_address']} "
          f"enemy={metadata['streams']['ENEMY']['cpu_address']}")


if __name__ == "__main__":
    main()
