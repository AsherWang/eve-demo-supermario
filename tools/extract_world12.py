"""Extract World 1-2 streams, terrain tables and sprites from the verified ROM."""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

from extract_smb_assets import find_once, compose_sprite, compose_metatile, METATILE_COUNTS

ROOT = Path(__file__).resolve().parents[1]
EXPECTED = 'f61548fdf1670cffefcc4f0b7bdcdd9eaba0c226e3b74f8666071496988248de'
SIGNATURES = {
    'AREA': ('480f0e015e02a700bc73', 0xfd),
    'ENEMIES': ('0b861a06db06dec202f03b', 0xff),
    'INTRO': ('38110f26ad403dc7', 0xfd),
    'BONUS': ('48010e01005a3e06454647465344ae01df4a4dc7', 0xfd),
}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--rom', type=Path, default=ROOT / 'roms/Super Mario Bros. (World).nes')
    parser.add_argument('--output', type=Path, default=ROOT / 'scripts/generated/world12_data.nut')
    args = parser.parse_args()
    raw = args.rom.read_bytes()
    if hashlib.sha256(raw).hexdigest() != EXPECTED:
        parser.error('ROM does not match the verified baseline')
    prg, chr_data = raw[16:32784], raw[32784:40976]
    metadata = {'rom_sha256': EXPECTED, 'streams': {}}
    lines = ['// Generated by tools/extract_world12.py from the verified ROM.']
    for name, (signature, terminator) in SIGNATURES.items():
        start = find_once(prg, bytes.fromhex(signature), name)
        data = prg[start:prg.index(terminator, start) + 1]
        metadata['streams'][name] = {'cpu_address': hex(0x8000 + start), 'length': len(data),
                                      'sha256': hashlib.sha256(data).hexdigest()}
        lines.append(f'ROM_WORLD_1_2_{name} <- [' + ','.join(str(v) for v in data) + '];')
    masks = bytes.fromhex('00000018011807180f18ff18011f071f0f1f811f01008f1ff11ff918f118ff1f')
    offset = find_once(prg, masks, 'TerrainRenderBits')
    lines.append('ROM_TERRAIN_MASKS <- [' + ','.join(str(v) for v in prg[offset:offset+32]) + '];')
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    out = ROOT / 'assets/world12'
    out.mkdir(parents=True, exist_ok=True)
    # EnemyGfxTable contains six tile IDs per 16x24 frame; piranhas mirror
    # their right-hand cells. ROM sprite palette 1 is shared with green koopas.
    graphics = find_once(prg, bytes.fromhex('fcfcaaabacadfcfcaeafb0b1'), 'EnemyGraphicsTable')
    palette_at = find_once(prg, bytes.fromhex('3f00200f291a090f3c1c0f0f30211c0f27171c'), 'underground palette')
    palette = list(prg[palette_at+3+20:palette_at+3+24])
    for frame in range(2):
        tiles = prg[graphics + (32+frame)*6:graphics+(33+frame)*6]
        compose_sprite(chr_data, tiles, palette, 3, mirror_right=True).save(out / f'piranha-{frame}.png')
    goomba_palette = list(prg[palette_at+3+28:palette_at+3+32])
    tiles = prg[graphics+14*6:graphics+15*6]
    goomba = compose_sprite(chr_data, tiles, goomba_palette, 3)
    from PIL import Image
    goomba.save(out / 'goomba-0.png')
    goomba.transpose(Image.Transpose.FLIP_LEFT_RIGHT).save(out / 'goomba-1.png')
    tiles = prg[graphics+23*6:graphics+24*6]
    compose_sprite(chr_data, tiles, goomba_palette, 3, flip_x_indices={5}, flip_y_indices={4,5}).save(out/'goomba-defeated.png')
    # DrawLargePlatform: three 16px sections assembled from CHR $75,$76,$77.
    from extract_smb_assets import tile_image
    from PIL import Image
    platform = Image.new('RGBA', (48, 8))
    platform_palette = list(prg[palette_at+3+24:palette_at+3+28])
    for index in range(6):
        platform.paste(tile_image(chr_data, 0x5b, platform_palette, 0, True), (index*8, 0))
    platform.save(out / 'platform.png')
    metatile_at=find_once(prg,bytes.fromhex('242424242727272724242435'),'MetatileGraphics')
    colour_at=find_once(prg,bytes.fromhex('272727170717'),'ColorRotatePalette')
    colours=prg[colour_at:colour_at+6]
    question_offset=metatile_at+sum(METATILE_COUNTS[:3])*4
    for frame,colour in enumerate(colours):
        question_palette=list(prg[palette_at+3+12:palette_at+3+16])
        question_palette[1]=colour
        compose_metatile(chr_data,prg[question_offset:question_offset+4],question_palette).save(out/f'question-{frame}.png')
    cursor=metatile_at
    for group,count in enumerate(METATILE_COUNTS):
        for index in range(count):
            palette=list(prg[palette_at+3+group*4:palette_at+7+group*4])
            compose_metatile(chr_data,prg[cursor:cursor+4],palette).save(out/f'metatile-{group*64+index}.png')
            cursor+=4
    (out / 'manifest.json').write_text(json.dumps(metadata, indent=2)+'\n', encoding='utf-8')
    print(args.output)


if __name__ == '__main__':
    main()
