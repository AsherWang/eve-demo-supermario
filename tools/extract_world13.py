"""Extract World 1-3 streams, terrain tables and exact ROM metatiles."""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

from PIL import Image

from extract_smb_assets import (
    METATILE_COUNTS,
    compose_metatile,
    compose_koopa_shell,
    compose_sprite,
    find_once,
    tile_image,
)


ROOT = Path(__file__).resolve().parents[1]
EXPECTED = "f61548fdf1670cffefcc4f0b7bdcdd9eaba0c226e3b74f8666071496988248de"
SIGNATURES = {
    "AREA": ("90110f26fe102a938717a314", 0xFD),
    "ENEMIES": ("2bd7e303c286e20676a5a38f", 0xFF),
}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--rom", type=Path, default=ROOT / "roms/Super Mario Bros. (World).nes"
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=ROOT / "scripts/generated/world13_data.nut",
    )
    args = parser.parse_args()
    raw = args.rom.read_bytes()
    if hashlib.sha256(raw).hexdigest() != EXPECTED:
        parser.error("ROM does not match the verified baseline")
    prg, chr_data = raw[16:32784], raw[32784:40976]
    metadata: dict = {"rom_sha256": EXPECTED, "streams": {}, "graphics": {}}
    lines = ["// Generated by tools/extract_world13.py from the verified ROM."]
    for name, (signature, terminator) in SIGNATURES.items():
        start = find_once(prg, bytes.fromhex(signature), f"World 1-3 {name}")
        data = prg[start : prg.index(terminator, start) + 1]
        metadata["streams"][name] = {
            "cpu_address": hex(0x8000 + start),
            "length": len(data),
            "sha256": hashlib.sha256(data).hexdigest(),
        }
        lines.append(
            f"ROM_WORLD_1_3_{name} <- ["
            + ",".join(str(value) for value in data)
            + "];"
        )
    masks = bytes.fromhex(
        "00000018011807180f18ff18011f071f0f1f811f01008f1ff11ff918f118ff1f"
    )
    mask_offset = find_once(prg, masks, "TerrainRenderBits")
    mask_data = prg[mask_offset : mask_offset + 32]
    lines.append(
        "ROM_WORLD_1_3_TERRAIN_MASKS <- ["
        + ",".join(str(value) for value in mask_data)
        + "];"
    )
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")

    palette_offset = find_once(
        prg,
        bytes.fromhex("3f00200f291a0f0f36170f0f30210f0f27170f"),
        "ground palette",
    )
    palettes = list(prg[palette_offset + 3 : palette_offset + 35])
    background_palettes = [palettes[index : index + 4] for index in range(0, 16, 4)]
    sprite_palettes = [palettes[index : index + 4] for index in range(16, 32, 4)]
    graphics_offset = find_once(
        prg, bytes.fromhex("242424242727272724242435"), "MetatileGraphics"
    )
    color_offset = find_once(prg, bytes.fromhex("272727170717"), "ColorRotatePalette")
    colors = prg[color_offset : color_offset + 6]

    out = ROOT / "assets/world13"
    out.mkdir(parents=True, exist_ok=True)
    for stale in out.glob("*.png"):
        stale.unlink()
    cursor = graphics_offset
    for group, count in enumerate(METATILE_COUNTS):
        for index in range(count):
            image = compose_metatile(
                chr_data,
                prg[cursor : cursor + 4],
                background_palettes[group],
            )
            image.save(out / f"metatile-{group * 64 + index}.png")
            cursor += 4
    # The one item block in 1-3 is metatile $c1. Its question-mark colour
    # rotates through the six ColorRotatePalette values while gameplay runs.
    question_tiles = prg[
        graphics_offset
        + sum(METATILE_COUNTS[:3]) * 4
        + 4 : graphics_offset
        + sum(METATILE_COUNTS[:3]) * 4
        + 8
    ]
    for frame, colour in enumerate(colors):
        palette = list(background_palettes[3])
        palette[1] = colour
        compose_metatile(chr_data, question_tiles, palette).save(
            out / f"question-{frame}.png"
        )
    # DrawLargePlatform uses background tile $5b; the three sections form the
    # 48-pixel ROM platform with the shared sprite palette.
    platform = Image.new("RGBA", (48, 8))
    for index in range(6):
        platform.alpha_composite(
            tile_image(chr_data, 0x5B, sprite_palettes[2], 0, True),
            (index * 8, 0),
        )
    platform.save(out / "platform.png")
    enemy_graphics = find_once(
        prg, bytes.fromhex("fcfcaaabacadfcfcaeafb0b1"), "enemy graphics table"
    )
    # ENEMY_NAMES index 39 is Bullet Bill; EnemyGfxTable stores six CHR cells.
    bullet_tiles = prg[enemy_graphics + 39 * 6 : enemy_graphics + 40 * 6]
    compose_sprite(chr_data, bullet_tiles, sprite_palettes[3], 3).save(
        out / "bullet-bill.png"
    )

    def enemy_frame(enemy_index):
        return prg[
            enemy_graphics + enemy_index * 6 : enemy_graphics + (enemy_index + 1) * 6
        ]

    def save_enemy_pair(filename, enemy_index):
        frame = prg[
            enemy_graphics + enemy_index * 6 : enemy_graphics + (enemy_index + 1) * 6
        ]
        image = compose_sprite(chr_data, frame, sprite_palettes[2], 3)
        image.save(out / (filename + "-right.png"))
        image.transpose(Image.Transpose.FLIP_LEFT_RIGHT).save(
            out / (filename + "-left.png")
        )

    # EnemyGfxTableOffsets uses the same koopa and paratroopa CHR frames for
    # green and red objects; EnemyAttributeData selects sprite palette 2 for
    # RedKoopa and RedParatroopa.
    for frame, enemy_index in enumerate((2, 3)):
        save_enemy_pair(f"red-koopa-{frame}", enemy_index)
    for frame, enemy_index in enumerate((4, 5)):
        save_enemy_pair(f"red-paratroopa-{frame}", enemy_index)
    for frame, enemy_index in enumerate((17, 18)):
        compose_koopa_shell(
            chr_data, enemy_frame(enemy_index), sprite_palettes[2],
            right_side_up=False,
        ).save(out / f"red-shell-{frame}.png")

    metadata["graphics"] = {
        "palette_cpu_address": hex(0x8000 + palette_offset),
        "metatile_cpu_address": hex(0x8000 + graphics_offset),
        "metatile_ids": [
            group * 64 + index
            for group, count in enumerate(METATILE_COUNTS)
            for index in range(count)
        ],
        "question_frames": len(colors),
        "platform_cpu_tile": "$5b",
        "bullet_bill_enemy_graphics_index": 39,
        "red_koopa_enemy_graphics_indices": [2, 3],
        "red_paratroopa_enemy_graphics_indices": [4, 5],
        "red_shell_enemy_graphics_indices": [17, 18],
        "red_enemy_sprite_palette": sprite_palettes[2],
    }
    (out / "manifest.json").write_text(
        json.dumps(metadata, indent=2) + "\n", encoding="utf-8", newline="\n"
    )
    print(args.output)


if __name__ == "__main__":
    main()
