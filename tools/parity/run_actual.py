from __future__ import annotations

import argparse
import json
import subprocess
import time
from datetime import datetime, timezone
from pathlib import Path

from common import expand_input_masks, load_movie, sha256_file, tool_path


DISABLED_SOURCE = """// Generated by tools/parity/run_actual.py for local parity runs.
// The checked-in/default form keeps parity mode disabled.
PARITY_MOVIE_ENABLED <- false;
PARITY_MOVIE_NAME <- \"disabled\";
PARITY_OUTPUT_DIR <- \"local-parity/actual/disabled\";
PARITY_FRAME_MASKS <- [];
PARITY_CAPTURE_FRAMES <- [];
"""


def write_generated_source(path: Path, source: str) -> None:
    """Write the hot-reloaded parity adapter despite transient Windows locks."""
    last_error: OSError | None = None
    for attempt in range(20):
        try:
            path.write_text(source, encoding="utf-8", newline="\n")
            return
        except OSError as error:
            last_error = error
            if attempt == 19:
                break
            time.sleep(0.05 * (attempt + 1))
    assert last_error is not None
    raise last_error


def squirrel_source(movie: dict, output: Path) -> str:
    masks = expand_input_masks(movie)
    output_text = str(output.resolve()).replace("\\", "/").replace('"', '\\"')
    movie_name = movie["name"].replace("\\", "\\\\").replace('"', '\\"')
    rows = []
    for start in range(0, len(masks), 32):
        rows.append("    " + ", ".join(str(value) for value in masks[start:start + 32]))
    captures = ", ".join(str(value) for value in movie.get("capture_frames", range(movie["frames"])))
    return f"""// Generated local replay. Do not package this file.
PARITY_MOVIE_ENABLED <- true;
PARITY_START_LEVEL <- {movie.get('level', 1)};
PARITY_MOVIE_NAME <- \"{movie_name}\";
PARITY_OUTPUT_DIR <- \"{output_text}\";
PARITY_FRAME_MASKS <- [
{',\n'.join(rows)}
];
PARITY_CAPTURE_FRAMES <- [{captures}];
"""


def main() -> int:
    parser = argparse.ArgumentParser(description="Replay a parity movie in the EVEngine remake.")
    parser.add_argument("--movie", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--project", type=Path, default=Path(__file__).resolve().parents[2])
    parser.add_argument(
        "--eve",
        type=Path,
        default=tool_path("eve"),
    )
    parser.add_argument("--timeout", type=float, default=120.0)
    args = parser.parse_args()

    movie_path = args.movie.resolve()
    movie = load_movie(movie_path)
    output = args.output.resolve()
    frames = output / "frames"
    frames.mkdir(parents=True, exist_ok=True)
    for stale in frames.glob("frame-*.png"):
        stale.unlink()

    generated = args.project.resolve() / "scripts" / "generated" / "parity_movie.nut"
    write_generated_source(generated, squirrel_source(movie, output))
    log_path = output / "eve-parity.log"
    command = [str(args.eve.resolve()), "run", "-l", str(log_path), str(args.project.resolve())]
    process = None
    stdout_log = None
    stderr_log = None
    try:
        stdout_log = (output / "process-stdout.log").open("w", encoding="utf-8")
        stderr_log = (output / "process-stderr.log").open("w", encoding="utf-8")
        process = subprocess.Popen(
            command,
            cwd=args.project.resolve(),
            stdout=stdout_log,
            stderr=stderr_log,
            text=True,
        )
        final_frame = frames / f"frame-{movie['frames'] - 1:06d}.png"
        deadline = time.monotonic() + args.timeout
        while time.monotonic() < deadline:
            if process.poll() is not None:
                break
            if final_frame.is_file() and final_frame.stat().st_size > 0:
                time.sleep(0.25)
                break
            time.sleep(0.05)
        if not final_frame.is_file():
            raise RuntimeError(f"EVEngine did not produce {final_frame} before exit/timeout")
    finally:
        if process is not None and process.poll() is None:
            process.terminate()
            try:
                process.wait(timeout=5)
            except subprocess.TimeoutExpired:
                process.kill()
                process.wait(timeout=5)
        if stdout_log is not None:
            stdout_log.close()
        if stderr_log is not None:
            stderr_log.close()
        write_generated_source(generated, DISABLED_SOURCE)

    states = []
    events = []
    trace_sources = [log_path, output / "process-stdout.log"]
    for trace_source in trace_sources:
        if not trace_source.is_file():
            continue
        for line in trace_source.read_text(encoding="utf-8", errors="replace").splitlines():
            marker = "PARITY_STATE "
            marker_at = line.find(marker)
            if marker_at < 0:
                continue
            payload = line[marker_at + len(marker):].strip()
            try:
                states.append(json.loads(payload))
            except json.JSONDecodeError:
                pass
        for line in trace_source.read_text(encoding="utf-8", errors="replace").splitlines():
            marker = "PARITY_EVENT "
            marker_at = line.find(marker)
            if marker_at < 0:
                continue
            payload = line[marker_at + len(marker):].strip()
            try:
                events.append(json.loads(payload))
            except json.JSONDecodeError:
                pass
    (output / "state.jsonl").write_text(
        "".join(json.dumps(item, ensure_ascii=False, separators=(",", ":")) + "\n" for item in states),
        encoding="utf-8",
    )
    events.sort(key=lambda item: (item["frame"], item["sequence"]))
    (output / "events.jsonl").write_text(
        "".join(json.dumps(item, ensure_ascii=False, separators=(",", ":")) + "\n" for item in events),
        encoding="utf-8",
    )
    manifest = {
        "schema": "smb-parity-artifact-v1",
        "producer": "evengine-remake",
        "created_utc": datetime.now(timezone.utc).isoformat(),
        "movie": movie["name"],
        "movie_sha256": sha256_file(movie_path),
        "comparison_frames": movie["frames"],
        "captured_frames": len(list(frames.glob("frame-*.png"))),
        "state_rows": len(states),
        "event_rows": len(events),
    }
    (output / "manifest.json").write_text(
        json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    print(f"actual artifacts: {output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
