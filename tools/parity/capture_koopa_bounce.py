"""Capture a controlled ROM stomp/recontact trace, not whole-level evidence."""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import subprocess

from common import sha256_file, tool_path
from run_reference import EXPECTED_ROM_SHA256

ROOT = Path(__file__).resolve().parents[2]


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--rom', type=Path, default=ROOT/'roms/Super Mario Bros. (World).nes')
    parser.add_argument('--origin-state', type=Path, required=True)
    parser.add_argument('--output', type=Path, default=ROOT/'local-parity/koopa-bounce')
    parser.add_argument('--write-fixture', action='store_true')
    args = parser.parse_args()
    if sha256_file(args.rom) != EXPECTED_ROM_SHA256:
        parser.error('unverified ROM')
    output = args.output.resolve()
    output.mkdir(parents=True, exist_ok=True)
    trace = output/'reference.jsonl'
    trace.unlink(missing_ok=True)
    template = ROOT/'tests/parity/fixtures/koopa-bounce.lua.in'
    source = template.read_text(encoding='utf-8').replace(
        '__OUTPUT_PATH__', json.dumps(trace.as_posix(), ensure_ascii=False))
    script = output/'capture.lua'
    script.write_text(source, encoding='utf-8')
    result = subprocess.run([
        str(tool_path('mesen')), str(args.rom.resolve()), '--load-state',
        str(args.origin_state.resolve()), '--frames', '45', '--home', str(output/'home'),
        '--lua', str(script), '--lua-allow-io', '--timeout', '30',
    ], capture_output=True, text=True, encoding='utf-8', timeout=40)
    (output/'run.log').write_text(result.stdout+result.stderr, encoding='utf-8')
    if result.returncode or not trace.is_file():
        raise RuntimeError(f'ROM capture failed: {output / "run.log"}')
    rows = [json.loads(line) for line in trace.read_text().splitlines()]
    if [row['frame'] for row in rows] != list(range(1, 41)):
        raise RuntimeError('ROM fixture did not produce the complete 40-frame trace')
    if rows[0]['enemy_state'] != 4 or not rows[-1]['enemy_state'] & 128:
        raise RuntimeError('ROM fixture did not stomp then kick the stationary shell')
    (output/'manifest.json').write_text(json.dumps({
        'rom_sha256': sha256_file(args.rom), 'origin_sha256': sha256_file(args.origin_state),
        'mesen_sha256': sha256_file(tool_path('mesen')), 'template_sha256': sha256_file(template),
        'trace_sha256': sha256_file(trace), 'frames': 40,
        'scope': 'RAM-seeded small-Mario ground-koopa stomp and shell recontact',
    }, indent=2)+'\n', encoding='utf-8')
    if args.write_fixture:
        data = [[row[key] for key in ('y', 'speed', 'force', 'dummy', 'enemy_state')] for row in rows]
        (ROOT/'scripts/generated/koopa_bounce_trace.nut').write_text(
            '// Generated by tools/parity/capture_koopa_bounce.py from the verified ROM.\n'
            '// [player canonical Y, Y speed, velocity fraction, position fraction, enemy state]\n'
            'KOOPA_BOUNCE_TRACE <- [\n'+',\n'.join(str(row) for row in data)+'\n];\n',
            encoding='utf-8')
    print(f'Captured {len(rows)} controlled ROM frames: {trace}')


if __name__ == '__main__':
    main()
