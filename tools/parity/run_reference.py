from __future__ import annotations

import argparse
import json
import os
import re
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

from common import load_movie, mesen_section_input_arguments, sha256_file


EXPECTED_ROM_SHA256 = "f61548fdf1670cffefcc4f0b7bdcdd9eaba0c226e3b74f8666071496988248de"


def lua_string(value: str) -> str:
    return json.dumps(value.replace("\\", "/"), ensure_ascii=False)


def build_capture_lua(output: Path, movie: dict) -> str:
    captures = movie.get("capture_frames", list(range(movie["frames"])))
    capture_map = ",\n".join(f"  [{frame}] = {frame}" for frame in captures)
    frame_dir = lua_string(str((output / "frames").resolve()))
    ram_trace = lua_string(str((output / "ram-trace.jsonl").resolve()))
    apu_trace = lua_string(str((output / "apu-writes.jsonl").resolve()))
    queue_trace = lua_string(str((output / "audio-queues.jsonl").resolve()))
    return f"""-- Generated by run_reference.py. Local test artifact only.
local comparisonFrame = 0
local frameDirectory = {frame_dir}
local ramTracePath = {ram_trace}
local ramTrace = assert(io.open(ramTracePath, "wb"))
local apuTrace = assert(io.open({apu_trace}, "wb"))
local queueTrace = assert(io.open({queue_trace}, "wb"))
local apuSequence = 0
local queueSequence = 0
local captureMap = {{
{capture_map}
}}

emu.addMemoryCallback(function(address, value)
  if address ~= 0x4014 then
    apuTrace:write(string.format('{{"frame":%d,"sequence":%d,"address":%d,"value":%d}}',
      comparisonFrame, apuSequence, address, value))
    apuTrace:write(string.char(10))
    apuSequence = apuSequence + 1
  end
end, emu.callbackType.write, 0x4000, 0x4017)

emu.addMemoryCallback(function(address, value)
  queueTrace:write(string.format('{{"frame":%d,"sequence":%d,"address":%d,"value":%d}}',
    comparisonFrame, queueSequence, address, value))
  queueTrace:write(string.char(10))
  queueSequence = queueSequence + 1
end, emu.callbackType.write, 0x00fa, 0x00ff)

emu.addEventCallback(function()
  local captureFrame = captureMap[comparisonFrame]
  if captureFrame ~= nil then
    local path = string.format("%s/frame-%06d.png", frameDirectory, captureFrame)
    local file = assert(io.open(path, "wb"))
    file:write(emu.takeScreenshot())
    file:close()
  end

  local bytes = {{}}
  for address = 0, 2047 do
    bytes[#bytes + 1] = string.format("%02x", emu.read(address, emu.memType.nesInternalRam))
  end
  ramTrace:write(string.format('{{"frame":%d,"ram_hex":"%s"}}', comparisonFrame, table.concat(bytes)))
  ramTrace:write(string.char(10))
  ramTrace:flush()
  apuTrace:flush()
  queueTrace:flush()
  comparisonFrame = comparisonFrame + 1
  apuSequence = 0
  queueSequence = 0
end, emu.eventType.endFrame)
"""


def build_origin_lua() -> str:
    # SMBDIS RAM symbols: OperMode=$0770 and GameEngineSubroutine=$000e.
    # Subroutine 8 is PlayerCtrlRoutine, the first normal controllable state.
    return """-- Report the first completed normal gameplay frame.
local absoluteFrame = 0
local found = false
emu.addEventCallback(function()
  local operMode = emu.read(0x0770, emu.memType.nesInternalRam)
  local operModeTask = emu.read(0x0772, emu.memType.nesInternalRam)
  local engineTask = emu.read(0x000e, emu.memType.nesInternalRam)
  local screenDisabled = emu.read(0x0774, emu.memType.nesInternalRam)
  if not found and operMode == 1 and operModeTask == 3 and engineTask == 8 and screenDisabled == 0 then
    found = true
    emu.log(string.format("PARITY_ORIGIN frame=%d oper_mode=1 oper_mode_task=3 game_engine_subroutine=8", absoluteFrame))
  end
  absoluteFrame = absoluteFrame + 1
end, emu.eventType.endFrame)
"""


def run_command(command: list[str], stdout_path: Path, stderr_path: Path) -> tuple[subprocess.CompletedProcess[str], list[dict]]:
    completed = subprocess.run(command, capture_output=True, text=True, encoding="utf-8")
    stdout_path.write_text(completed.stdout, encoding="utf-8", newline="\n")
    stderr_path.write_text(completed.stderr, encoding="utf-8", newline="\n")
    summaries = []
    for line in completed.stdout.splitlines():
        try:
            event = json.loads(line)
        except json.JSONDecodeError:
            continue
        if event.get("event") == "summary":
            summaries.append(event)
    return completed, summaries


def main() -> int:
    parser = argparse.ArgumentParser(description="Run the ROM in the headless Mesen reference core.")
    parser.add_argument("--rom", type=Path, required=True)
    parser.add_argument("--movie", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument(
        "--mesen-agent",
        type=Path,
        default=Path.home() / ".local" / "bin" / "mesen-agent.exe",
    )
    parser.add_argument("--allow-other-rom", action="store_true")
    args = parser.parse_args()

    rom = args.rom.resolve()
    movie_path = args.movie.resolve()
    output = args.output.resolve()
    if not rom.is_file():
        parser.error(f"ROM not found: {rom}")
    if not args.mesen_agent.is_file():
        parser.error(f"mesen-agent not found: {args.mesen_agent}")

    movie = load_movie(movie_path)
    rom_hash = sha256_file(rom)
    if rom_hash != EXPECTED_ROM_SHA256 and not args.allow_other_rom:
        parser.error(
            f"ROM SHA-256 mismatch: {rom_hash}; expected {EXPECTED_ROM_SHA256}. "
            "Use --allow-other-rom only for an intentional new baseline."
        )

    frames_dir = output / "frames"
    frames_dir.mkdir(parents=True, exist_ok=True)
    for stale in frames_dir.glob("frame-*.png"):
        stale.unlink()
    home = output / "mesen-home"
    home.mkdir(parents=True, exist_ok=True)
    bootstrap = movie.get("reference_bootstrap", {})
    bootstrap_frames = bootstrap.get("frames", 0)
    origin_lua = output / "find-origin.lua"
    origin_lua.write_text(build_origin_lua(), encoding="utf-8", newline="\n")
    origin_state = output / "origin.mss"
    scan_command = [
        str(args.mesen_agent.resolve()),
        str(rom),
        "--home", str(home),
        "--frames", str(bootstrap_frames),
        "--timeout", "120",
        "--lua", str(origin_lua),
    ]
    scan_command.extend(mesen_section_input_arguments(bootstrap.get("inputs", [])))
    scan_result, scan_summaries = run_command(
        scan_command,
        output / "origin-scan-events.jsonl",
        output / "origin-scan-stderr.log",
    )
    if scan_result.returncode != 0 or not scan_summaries or not scan_summaries[-1].get("ok"):
        print(f"reference origin scan failed; inspect {output / 'origin-scan-stderr.log'}", file=sys.stderr)
        return scan_result.returncode or 1
    origin_match = re.search(r"PARITY_ORIGIN frame=(\d+)", scan_result.stdout)
    if not origin_match:
        print("reference bootstrap did not reach normal SMB player control", file=sys.stderr)
        return 1
    origin_frame = int(origin_match.group(1))

    bootstrap_command = [
        str(args.mesen_agent.resolve()),
        str(rom),
        "--home", str(home),
        "--frames", str(origin_frame + 1),
        "--timeout", "120",
        "--save-state", str(origin_state),
    ]
    bootstrap_command.extend(mesen_section_input_arguments(bootstrap.get("inputs", [])))
    bootstrap_result, bootstrap_summaries = run_command(
        bootstrap_command,
        output / "bootstrap-events.jsonl",
        output / "bootstrap-stderr.log",
    )
    if (bootstrap_result.returncode != 0 or not bootstrap_summaries or
            not bootstrap_summaries[-1].get("ok") or not origin_state.is_file()):
        print(f"reference bootstrap replay failed; inspect {output / 'bootstrap-stderr.log'}", file=sys.stderr)
        return bootstrap_result.returncode or 1

    lua_path = output / "capture.lua"
    lua_path.write_text(build_capture_lua(output, movie), encoding="utf-8", newline="\n")
    command = [
        str(args.mesen_agent.resolve()),
        str(rom),
        "--home", str(home),
        "--load-state", str(origin_state),
        "--frames", str(movie["frames"]),
        "--timeout", "120",
        "--lua", str(lua_path),
        "--lua-allow-io",
        "--audio", str(output / "audio.wav"),
        "--state-json", str(output / "state-final.json"),
        "--dump-memory", f"NesInternalRam:0:2048={output / 'ram-final.bin'}",
    ]
    command.extend(mesen_section_input_arguments(movie.get("inputs", [])))
    completed, summaries = run_command(command, output / "events.jsonl", output / "stderr.log")

    manifest = {
        "schema": "smb-parity-artifact-v1",
        "producer": "mesen-agent-reference",
        "created_utc": datetime.now(timezone.utc).isoformat(),
        "rom_sha256": rom_hash,
        "movie_sha256": sha256_file(movie_path),
        "movie": movie["name"],
        "comparison_frames": movie["frames"],
        "reference_bootstrap_frames": bootstrap_frames,
        "detected_origin_frame": origin_frame,
        "origin_rule": {"oper_mode_address": "0x0770", "oper_mode": 1,
                        "oper_mode_task_address": "0x0772", "oper_mode_task": 3,
                        "engine_subroutine_address": "0x000e", "engine_subroutine": 8},
        "origin_scan_summary": scan_summaries[-1],
        "origin_replay_summary": bootstrap_summaries[-1],
        "capture_frames": movie.get("capture_frames", list(range(movie["frames"]))),
        "mesen_agent_sha256": sha256_file(args.mesen_agent),
        "exit_code": completed.returncode,
        "summary": summaries[-1] if summaries else None,
    }
    (output / "manifest.json").write_text(
        json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    if completed.returncode != 0 or not summaries or not summaries[-1].get("ok"):
        print(f"reference run failed; inspect {output / 'stderr.log'}", file=sys.stderr)
        return completed.returncode or 1
    print(f"reference artifacts: {output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
