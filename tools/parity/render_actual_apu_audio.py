from __future__ import annotations

import argparse
import hashlib
import json
import subprocess
import sys
import wave
from collections import defaultdict
from pathlib import Path

from common import load_movie, mesen_section_input_arguments, sha256_file


def load_writes(path: Path, frames: int) -> dict[int, list[dict[str, int]]]:
    grouped: dict[int, list[dict[str, int]]] = defaultdict(list)
    with path.open("r", encoding="utf-8") as source:
        for line_number, line in enumerate(source, 1):
            if not line.strip():
                continue
            row = json.loads(line)
            frame = row.get("frame")
            sequence = row.get("sequence")
            address = row.get("address")
            value = row.get("value")
            if not all(isinstance(item, int) for item in (frame, sequence, address, value)):
                raise ValueError(f"invalid APU row {line_number}: {row!r}")
            if not 0 <= frame < frames:
                raise ValueError(f"APU row {line_number} frame is outside capture: {frame}")
            expected_sequence = len(grouped[frame])
            if sequence != expected_sequence:
                raise ValueError(
                    f"APU row {line_number} sequence: expected {expected_sequence}, got {sequence}"
                )
            grouped[frame].append({"address": address, "value": value})
    return grouped


def lua_string(value: str) -> str:
    return json.dumps(value.replace("\\", "/"), ensure_ascii=False)


def build_lua(
    writes: dict[int, list[dict[str, int]]], diagnostics: Path, capture_frames: int
) -> str:
    frame_tables = []
    for frame in sorted(writes):
        rows = ",".join(
            f'{{address={row["address"]},value={row["value"]}}}' for row in writes[frame]
        )
        frame_tables.append(f"  [{frame}]={{{rows}}}")
    return f"""-- Generated by render_actual_apu_audio.py.
-- Mesen supplies only the cycle schedule and 2A03 hardware model.  Every
-- value written to the APU comes from the independent EVEngine-side model.
local comparisonFrame = 0
local sequence = 0
local captureFrames = {capture_frames}
local expected = {{
{',\n'.join(frame_tables)}
}}
local diagnostics = assert(io.open({lua_string(str(diagnostics.resolve()))}, "wb"))

local function isApuRegister(address)
  return address <= 0x4013 or address == 0x4015 or address == 0x4017
end

emu.addMemoryCallback(function(address, value)
  if not isApuRegister(address) then
    return
  end
  if comparisonFrame >= captureFrames then
    return value
  end
  local rows = expected[comparisonFrame] or {{}}
  local row = rows[sequence + 1]
  local replacement = 0
  local status = "unexpected_reference_write"
  local expectedAddress = -1
  local expectedValue = -1
  if row ~= nil then
    expectedAddress = row.address
    expectedValue = row.value
    replacement = row.value
    status = row.address == address and "injected" or "address_mismatch"
    if row.address ~= address then
      replacement = 0
    end
  end
  diagnostics:write(string.format('{{"frame":%d,"sequence":%d,"reference_address":%d,"reference_value":%d,"actual_address":%d,"actual_value":%d,"injected_value":%d,"status":"%s"}}',
    comparisonFrame, sequence, address, value, expectedAddress, expectedValue,
    replacement, status))
  diagnostics:write(string.char(10))
  sequence = sequence + 1
  return replacement
end, emu.callbackType.write, 0x4000, 0x4017)

emu.addEventCallback(function()
  local rows = expected[comparisonFrame] or {{}}
  while sequence < #rows do
    local row = rows[sequence + 1]
    diagnostics:write(string.format('{{"frame":%d,"sequence":%d,"reference_address":-1,"reference_value":-1,"actual_address":%d,"actual_value":%d,"injected_value":-1,"status":"missing_reference_write"}}',
      comparisonFrame, sequence, row.address, row.value))
    diagnostics:write(string.char(10))
    sequence = sequence + 1
  end
  diagnostics:flush()
  comparisonFrame = comparisonFrame + 1
  sequence = 0
end, emu.eventType.endFrame)
"""


def run_command(command: list[str], stdout_path: Path, stderr_path: Path) -> subprocess.CompletedProcess[str]:
    completed = subprocess.run(command, capture_output=True, text=True, encoding="utf-8")
    stdout_path.write_text(completed.stdout, encoding="utf-8", newline="\n")
    stderr_path.write_text(completed.stderr, encoding="utf-8", newline="\n")
    return completed


def wave_info(path: Path) -> dict[str, int]:
    with wave.open(str(path), "rb") as source:
        return {
            "channels": source.getnchannels(),
            "sample_width": source.getsampwidth(),
            "sample_rate": source.getframerate(),
            "sample_frames": source.getnframes(),
        }


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Render modeled APU values with the reference cycle schedule and Mesen 2A03."
    )
    parser.add_argument("--rom", type=Path, required=True)
    parser.add_argument("--movie", type=Path, required=True)
    parser.add_argument("--origin-state", type=Path, required=True)
    parser.add_argument("--apu-writes", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument(
        "--mesen-agent", type=Path,
        default=Path.home() / ".local" / "bin" / "mesen-agent.exe",
    )
    args = parser.parse_args()

    movie = load_movie(args.movie.resolve())
    frames = int(movie["frames"])
    writes = load_writes(args.apu_writes.resolve(), frames)
    output = args.output.resolve()
    output.parent.mkdir(parents=True, exist_ok=True)
    lua_path = output.with_name("apu-audio-replay.lua")
    diagnostics = output.with_name("apu-audio-replay.jsonl")
    lua_path.write_text(
        build_lua(writes, diagnostics, frames), encoding="utf-8", newline="\n"
    )

    command = [
        str(args.mesen_agent.resolve()), str(args.rom.resolve()),
        "--home", str(output.parent / "mesen-audio-home"),
        "--load-state", str(args.origin_state.resolve()),
        "--frames", str(frames),
        "--timeout", "120",
        "--lua", str(lua_path),
        "--lua-allow-io",
        "--audio", str(output),
    ]
    command.extend(mesen_section_input_arguments(movie.get("inputs", [])))
    completed = run_command(
        command,
        output.with_name("apu-audio-replay-events.jsonl"),
        output.with_name("apu-audio-replay-stderr.log"),
    )
    summaries = []
    for line in completed.stdout.splitlines():
        try:
            row = json.loads(line)
        except json.JSONDecodeError:
            continue
        if row.get("event") == "summary":
            summaries.append(row)
    if completed.returncode != 0 or not summaries or not summaries[-1].get("ok") or not output.is_file():
        print(f"APU audio replay failed; inspect {output.with_name('apu-audio-replay-stderr.log')}", file=sys.stderr)
        return completed.returncode or 1

    statuses: dict[str, int] = defaultdict(int)
    if diagnostics.is_file():
        for line in diagnostics.read_text(encoding="utf-8").splitlines():
            if line.strip():
                statuses[json.loads(line)["status"]] += 1
    manifest = {
        "schema": "smb-actual-apu-audio-v1",
        "renderer": "mesen-2a03-cycle-carrier",
        "cycle_schedule": "reference ROM execution",
        "register_values": "EVEngine-side source-derived APU model",
        "rom_sha256": sha256_file(args.rom.resolve()),
        "movie_sha256": sha256_file(args.movie.resolve()),
        "apu_writes_sha256": sha256_file(args.apu_writes.resolve()),
        "wav_sha256": hashlib.sha256(output.read_bytes()).hexdigest(),
        "wave": wave_info(output),
        "replay_statuses": dict(sorted(statuses.items())),
    }
    output.with_suffix(".manifest.json").write_text(
        json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    print(f"rendered cycle-timed APU audio: {output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
